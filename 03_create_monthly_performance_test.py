# MAIN
# ============================================================

def main():

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True
    )

    print("=" * 70)
    print(
        "INTAIN SYNTHETIC TEST DATA GENERATOR"
    )
    print("=" * 70)

    # --------------------------------------------------------
    # Load static loans
    # --------------------------------------------------------

    static_df = pd.read_csv(
        INPUT_FILE,
        parse_dates=[
            "origination_month"
        ]
    )

    print(
        f"Static loans loaded: "
        f"{len(static_df):,}"
    )

    # --------------------------------------------------------
    # Generate monthly records
    # --------------------------------------------------------

    all_records = []

    print("\nProcessing loan historical paths...")
    for index, loan in tqdm(static_df.iterrows(), total=len(static_df), desc="Generating Monthly Test Performance", bar_format="{l_bar}{bar:30}{r_bar}"):

        records = (
            generate_loan_test_history(
                loan
            )
        )

        all_records.extend(
            records
        )

    df = pd.DataFrame(
        all_records
    )

    # --------------------------------------------------------
    # Sort
    # --------------------------------------------------------

    df = df.sort_values(
        [
            "loan_id",
            "reporting_month"
        ]
    ).reset_index(
        drop=True
    )

    # --------------------------------------------------------
    # Validate
    # --------------------------------------------------------

    validate_test_data(
        df
    )

    # --------------------------------------------------------
    # Save
    # --------------------------------------------------------

    df.to_csv(
        OUTPUT_FILE,
        index=False
    )

    print("\n" + "=" * 70)
    print(
        "TEST DATA GENERATED SUCCESSFULLY"
    )
    print("=" * 70)

    print(
        f"Rows         : {len(df):,}"
    )

    print(
        f"Columns      : {len(df.columns)}"
    )

    print(
        f"Unique loans : "
        f"{df['loan_id'].nunique():,}"
    )

    print(
        f"Date range   : "
        f"{df['reporting_month'].min().date()} "
        f"→ "
        f"{df['reporting_month'].max().date()}"
    )

    print(
        f"Output       : "
        f"{OUTPUT_FILE}"
    )

    print(
        "\nTarget columns: NONE"
    )

    print("\nSample:")
    print(
        df.head()
    )


if __name__ == "__main__":
    main()